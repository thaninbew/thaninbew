// Exports the README banner's layers (heydot-marketing r5 variant "a", the generator of .github/assets/banner-light.png)
// as data for the card: the seeded dot scatter as static SVG, the speaker dot, the logo dot geometry, the kit's dot
// shapes (geometry only, coloured by the card), the bubble path.
// Run from this folder: HEYDOT_MARKETING=<path to heydot-marketing/design> node build-layers.mjs
import { writeFileSync, copyFileSync } from 'node:fs';
// Point HEYDOT_MARKETING at the heydot-marketing/design folder that generates the README banner.
const SRC = (process.env.HEYDOT_MARKETING ?? '').replace(/\/?$/, '/');
const { hx, DOT, litDotSVG, family } = await import(SRC + 'src/kit.mjs');
const { SHAPES } = await import(SRC + 'src/r2-banners.mjs');
const { VIOLET, LOGO, phosphorPath, scatter, TEXT_BOX } = await import(SRC + 'src/r4-banners.mjs');
const { VARIANTS } = await import(SRC + 'src/r5-banners.mjs');

// Same keep-out and recolouring as r5's banner(v, false).
const v = VARIANTS.find(x => x.key === 'a');
const { hero, speaker: sp, reply } = v, s = hero.size;
const heroBox = [hero.x - s * 0.08, hero.y - 10, hero.x + s * 1.05, hero.y + s];
const spBox = [sp.cx - sp.size * 0.45, sp.cy - sp.size * 0.45, sp.cx + sp.size * 0.45, sp.cy + sp.size * 0.45];
const keep = [TEXT_BOX, heroBox, spBox, [sp.bubble.x - 10, sp.bubble.y - 10, sp.bubble.x + 210, sp.bubble.y + 96], [reply.x - 10, reply.y - 10, reply.x + 320, reply.y + 96]];
const NOT_VIOLET = ['orchid', 'pink', 'blue', 'cyan', 'yellow', 'teal', 'coral'].map(k => hx(DOT[k]));
const dots = scatter({ ...v.dots, keep }).map((d, i) => (d.color === VIOLET ? { ...d, color: NOT_VIOLET[i % NOT_VIOLET.length] } : d));
const dotSVG = (shape, color, opts) => `<svg viewBox="0 0 96 96" style="overflow:visible;display:block;width:100%;height:100%">${litDotSVG(shape, family(color), opts)}</svg>`;

const out = {
  hero, reply, speakerBubble: sp.bubble,
  washAt: [hero.x + s / 2, hero.y + s / 2],
  dots: dots.map(d => ({ x: d.x, y: d.y, s: d.s, rot: d.rot, depth: d.depth,
    svg: dotSVG(SHAPES[d.kind], d.color, { shadowOpacity: 0.3, shadowDrop: 5, shadowBlur: 4 }) })),
  speaker: { cx: sp.cx, cy: sp.cy, s: sp.size, rot: sp.rot ?? 0,
    svg: dotSVG(SHAPES[sp.kind], hx(DOT[sp.color]), { shadowOpacity: 0.32, shadowDrop: 5, shadowBlur: 4 }) },
  logo: LOGO.dot,
  shapes: SHAPES,
  phosphorPath,
};
writeFileSync('layers.js', `// Generated by build-layers.mjs from the banner generator. Do not edit.\nwindow.LAYERS = ${JSON.stringify(out)};\n`);
copyFileSync(SRC + 'logos-r13/final/icon-1024.png', 'icon-1024.png');   // the coral Liquid Glass logo
console.log(dots.map(d => `${d.depth} ${d.x.toFixed(0)},${d.y.toFixed(0)} s${d.s.toFixed(0)}`).join('\n'));
console.log(JSON.stringify(LOGO.dot).slice(0, 600));
