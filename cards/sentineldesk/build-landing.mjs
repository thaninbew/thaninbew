// Exports the SentinelDesk landing page (gdg-hackathon docs/demo/index.html) as data for the card: its stylesheet,
// icon sprite and hero markup, laid out as a 1200 x 630 browser window shows it. The card draws the page's seeded sky
// itself and renders this inside a shadow root, so the page's class names never meet the card's.
// Build from main (the current brand: ice-to-blue AI accents, navy AI mark), not an older branch.
// Run from this folder: GDG=<path to a gdg-hackathon checkout on main> node build-landing.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const root = (process.env.GDG ?? '').replace(/\/?$/, '/');
const src = readFileSync(root + 'docs/demo/index.html', 'utf8');
const pick = (re, what) => { const m = src.match(re); if (!m) throw new Error('landing page changed: no ' + what); return m[1]; };

let css = pick(/<style>([\s\S]*?)<\/style>/, 'stylesheet');
const edits = [
  [':root{', ':host{'],                                      // tokens live on the shadow host
  ['html,body{margin:0}\n', ''],
  ['body{background:#fff;', '.page{'],                       // the card supplies the background
  ['min-height:100svh;display:flex', 'min-height:630px;display:flex'],
  ['padding:clamp(36px,8vh,88px) 0 0', 'padding:50px 0 0'], // 8vh of a 630 px window
  ['margin:clamp(40px,8vh,84px) auto 0', 'margin:50px auto 0'],
];
for (const [a, b] of edits) { if (!css.includes(a)) throw new Error('landing page changed: ' + a); css = css.replace(a, b); }

const sprite = pick(/(<svg width="0" height="0"[\s\S]*?<\/svg>)/, 'icon sprite');
const header = pick(/(<header class="hero[\s\S]*?<\/header>)/, 'hero')
  .replace(/\s*<div class="sky"[^>]*>[\s\S]*?<\/div><\/div>/, '');  // the card draws the sky
if (header.includes('class="sky"')) throw new Error('landing page changed: sky markup');

writeFileSync('landing.js', `// Generated by build-landing.mjs from gdg-hackathon docs/demo/index.html. Do not edit.\nwindow.LANDING = ${JSON.stringify({ css, sprite, header })};\n`);
console.log('landing.js', css.length, sprite.length, header.length);
